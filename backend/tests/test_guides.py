class _StatusError(Exception):
    def __init__(self, status_code):
        super().__init__(f"status {status_code}")
        self.status_code = status_code


def provider_with(calls: list) -> GeminiProvider:
    provider = GeminiProvider.__new__(GeminiProvider)
    provider.model, provider._timeout_s, provider._retries = "m", 0.2, 1

    async def fake_call(prompt):
        outcome = calls.pop(0)
        if isinstance(outcome, Exception):
            raise outcome
        if outcome == "hang":
            await asyncio.sleep(5)
        return GOOD

    provider._call = fake_call
    return provider


async def test_gemini_retries_transient_errors_once():
    calls = [_StatusError(503), "ok"]
    assert await provider_with(calls).generate("Plastic", None) == GOOD
    assert calls == []


async def test_gemini_does_not_retry_client_errors():
    calls = [_StatusError(400), "ok"]
    with pytest.raises(ProviderError) as exc:
        await provider_with(calls).generate("Plastic", None)
    assert exc.value.reason == "http_400" and calls == ["ok"]


async def test_gemini_timeout_is_bounded():
    calls = ["hang", "hang"]
    started = asyncio.get_running_loop().time()
    with pytest.raises(ProviderError) as exc:
        await provider_with(calls).generate("Plastic", None)
    assert exc.value.reason == "timeout"
    assert asyncio.get_running_loop().time() - started < 1.5
