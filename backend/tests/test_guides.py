import asyncio

import pytest

from app.errors import ApiError
from app.guides import GeminiProvider, GeneratedGuide, GuideService, ProviderError, sanitize_hint
from app.observability import Metrics
from app.schemas import GuideRequest, WasteClass

GOOD = GeneratedGuide(
    title="Bottle bird feeder",
    materials=["Plastic bottle", "Wooden spoons", "Bird seed"],
    steps=["Rinse the bottle.", "Push two spoons through the sides.", "Fill with seed and hang it up."],
    precautions=["Ask an adult to help make holes."],
)


class FakeProvider:
    name = "gemini"
    model = "fake-model"

    def __init__(self, result=GOOD, error: Exception | None = None, delay: float = 0):
        self.result, self.error, self.delay, self.calls = result, error, delay, 0

    async def generate(self, class_name, item_hint):
        self.calls += 1
        await asyncio.sleep(self.delay)
        if self.error:
            raise self.error
        return self.result


def service(provider=None) -> GuideService:
    return GuideService(provider, low_confidence=0.5, cache_ttl_s=60, cache_size=8, metrics=Metrics())


def request(name: str, confidence: float = 0.9, **extra) -> GuideRequest:
    return GuideRequest(class_name=WasteClass(name), confidence=confidence, **extra)


async def test_hazardous_always_uses_curated_disposal():
    provider = FakeProvider()
    guide, _ = await service(provider).get(request("Hazardous"))
    assert guide.source == "curated" and guide.kind == "disposal"
    assert provider.calls == 0
    assert "photo cannot confirm" in guide.safety_notice


async def test_low_confidence_requires_confirmation():
    with pytest.raises(ApiError) as exc:
        await service(FakeProvider()).get(request("Plastic", 0.3))
    assert exc.value.status == 409
    guide, _ = await service(FakeProvider()).get(request("Plastic", 0.3, confirmed_by_user=True))
    assert guide.source == "gemini"


async def test_generated_guide_is_labelled_cached_and_keeps_mandatory_precautions():
    provider = FakeProvider()
    svc = service(provider)
    guide, cached = await svc.get(request("Metal"))
    assert (guide.source, cached) == ("gemini", False)
    assert guide.source_detail == "Generated by fake-model"
    assert any("sharp edges" in p for p in guide.precautions)
    again, cached = await svc.get(request("Metal"))
    assert cached and provider.calls == 1 and again == guide


async def test_cache_key_includes_item_hint():
    provider = FakeProvider()
    svc = service(provider)
    await svc.get(request("Plastic", item_hint="bottle"))
    await svc.get(request("Plastic", item_hint="cup"))
    assert provider.calls == 2


@pytest.mark.parametrize("reason", ["timeout", "http_503", "schema", "unsafe_content"])
async def test_provider_failures_fall_back_to_labelled_curated_guide(reason):
    svc = service(FakeProvider(error=ProviderError(reason)))
    guide, _ = await svc.get(request("Plastic"))
    assert guide.source == "curated"
    assert "unavailable" in guide.source_detail
    assert svc.metrics.counters[f"guide_fallback_{reason}"] == 1


