import { render, screen, waitFor } from "@testing-library/react";
import userEvent from "@testing-library/user-event";
import { afterEach, vi } from "vitest";
import { matchItems } from "../api";
import type { ItemSummary } from "../types";
import { GuideSearch } from "./GuideSearch";

afterEach(() => vi.restoreAllMocks());

const items: ItemSummary[] = [
  { code: "001", name: "Water bottle", aliases: ["plastic bottle"], resin: { number: 1, type: "PET" } },
  { code: "002", name: "Soft drink bottle", aliases: ["soda bottle"], resin: { number: 1, type: "PET" } },
  { code: "005", name: "Yogurt cup", aliases: ["yoghurt pot"], resin: { number: 5, type: "PP" } },
];

const waterBottle = {
  ...items[0],
  recycling: { accepted: "Widely accepted.", steps: ["Empty it.", "Squash it.", "Bin it."] },
  upcycling: { title: "Self-watering planter", materials: ["Bottle"], steps: ["Cut.", "Thread.", "Plant."], precautions: [] },
  safety_notice: "A photo cannot confirm what an item contains or that it is safe to handle.",
  catalog_version: "1.0.0",
};

const json = (body: unknown, status = 200) => new Response(JSON.stringify(body), { status });

function mockApi(extra?: (url: string) => Response | undefined) {
  return vi.spyOn(globalThis, "fetch").mockImplementation(async (input) => {
    const url = String(input);
    const custom = extra?.(url);
    if (custom) return custom;
    if (url.endsWith("/v1/items")) return json({ version: "1.0.0", items });
    if (url.endsWith("/v1/items/001")) return json(waterBottle);
    return json({ error: { code: "item_not_found", message: "No item" } }, 404);
  });
}

it("matches codes, short codes and names", () => {
  expect(matchItems(items, "001").map((i) => i.code)).toEqual(["001"]);
  expect(matchItems(items, "1").map((i) => i.code)).toEqual(["001"]);
  expect(matchItems(items, "#5").map((i) => i.code)).toEqual(["005"]);
  expect(matchItems(items, "00").map((i) => i.code)).toEqual(["001", "002", "005"]);
  expect(matchItems(items, "soda").map((i) => i.code)).toEqual(["002"]);
  expect(matchItems(items, "")).toEqual([]);
});

it("typing a code shows the item's recycling and upcycling methods", async () => {
  mockApi();
  render(<GuideSearch material="Plastic" announce={() => {}} />);
  await waitFor(() => expect(screen.getByText("All item codes (3)")).toBeInTheDocument());

  await userEvent.type(screen.getByRole("searchbox", { name: "Item code or name" }), "001");
  await userEvent.click(screen.getByRole("button", { name: "Search" }));

  expect(await screen.findByRole("heading", { name: "Water bottle" })).toBeInTheDocument();
  expect(screen.getByLabelText("Item code 001")).toBeInTheDocument();
  expect(screen.getByRole("heading", { name: /Recycling/ })).toBeInTheDocument();
  expect(screen.getByRole("heading", { name: /Upcycling: Self-watering planter/ })).toBeInTheDocument();
});

it("an unknown code says so instead of guessing", async () => {
  mockApi();
  render(<GuideSearch material="Plastic" announce={() => {}} />);
  await waitFor(() => expect(screen.getByText("All item codes (3)")).toBeInTheDocument());
  await userEvent.type(screen.getByRole("searchbox", { name: "Item code or name" }), "777");
  await userEvent.click(screen.getByRole("button", { name: "Search" }));
  expect(await screen.findByText(/No item has the code 777/)).toBeInTheDocument();
});

it("free text with no coded match falls back to a labelled AI guide", async () => {
  const fetchMock = mockApi((url) =>
    url.endsWith("/v1/guides")
      ? json({
          api_version: "1",
          request_id: "g",
          cached: false,
          guide: {
            class_name: "Plastic",
            kind: "upcycle",
            title: "Toy car garage",
            materials: ["Box"],
            steps: ["One.", "Two.", "Three."],
            precautions: [],
            source: "gemini",
            source_detail: "Generated by gemini-3.5-flash-lite",
            safety_notice: "A photo cannot confirm what an item contains or that it is safe to handle.",
          },
        })
      : undefined,
  );
  render(<GuideSearch material="Plastic" announce={() => {}} />);
  await waitFor(() => expect(screen.getByText("All item codes (3)")).toBeInTheDocument());
  await userEvent.type(screen.getByRole("searchbox", { name: "Item code or name" }), "toy car");
  await userEvent.click(screen.getByRole("button", { name: "Search" }));
  expect(await screen.findByRole("heading", { name: "Toy car garage" })).toBeInTheDocument();
  expect(screen.getByText(/No coded item matches/)).toBeInTheDocument();
  const guideCall = fetchMock.mock.calls.find(([url]) => String(url).endsWith("/v1/guides"))!;
  expect(JSON.parse(String(guideCall[1]!.body)).item_hint).toBe("toy car");
});
