import { render, screen } from "@testing-library/react";
import userEvent from "@testing-library/user-event";
import { afterEach, vi } from "vitest";
import { GuideSearch } from "./GuideSearch";

afterEach(() => vi.restoreAllMocks());

const guideResponse = {
  api_version: "1",
  request_id: "g",
  cached: false,
  guide: {
    class_name: "Plastic",
    kind: "upcycle",
    title: "Yogurt cup seed starters",
    materials: ["Yogurt cups"],
    steps: ["One.", "Two.", "Three."],
    precautions: [],
    source: "gemini",
    source_detail: "Generated by gemini-3.5-flash-lite",
    safety_notice: "A photo cannot confirm what an item contains or that it is safe to handle.",
  },
};

it("searches a typed item and shows its guide", async () => {
  const fetchMock = vi
    .spyOn(globalThis, "fetch")
    .mockResolvedValue(new Response(JSON.stringify(guideResponse), { status: 200 }));
  render(<GuideSearch material="Plastic" announce={() => {}} />);

  expect(screen.getByRole("search")).toBeInTheDocument();
  await userEvent.type(screen.getByRole("searchbox", { name: "Plastic item name" }), "  yogurt cup ");
  await userEvent.click(screen.getByRole("button", { name: "Get guide" }));

  expect(await screen.findByRole("heading", { name: "Yogurt cup seed starters" })).toBeInTheDocument();
  expect(JSON.parse(String(fetchMock.mock.calls[0]![1]!.body))).toEqual({
    class_name: "Plastic",
    confidence: 1,
    confirmed_by_user: true,
    item_hint: "yogurt cup",
  });
});

it("example chips run a search directly", async () => {
  const fetchMock = vi
    .spyOn(globalThis, "fetch")
    .mockResolvedValue(new Response(JSON.stringify(guideResponse), { status: 200 }));
  render(<GuideSearch material="Plastic" announce={() => {}} />);
  await userEvent.click(screen.getByRole("button", { name: "plastic bag" }));
  await screen.findByRole("heading", { name: "Yogurt cup seed starters" });
  expect(JSON.parse(String(fetchMock.mock.calls[0]![1]!.body)).item_hint).toBe("plastic bag");
});

it("disables search for an empty query", () => {
  render(<GuideSearch material="Plastic" announce={() => {}} />);
  expect(screen.getByRole("button", { name: "Get guide" })).toBeDisabled();
});
